'use strict';
// Navigate to the exact standalone bytes, disable networking, then operate all three records.
const assert=require('node:assert/strict');
const {mkdtemp,readFile,rm}=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright-core');
async function main(){
  const output=process.argv[2];
  if(!output)throw Error('Supply the standalone HTML generated by build_preview.py.');
  const product=path.resolve(__dirname,'..'),scratch=await mkdtemp(path.join(os.tmpdir(),'ignition-preview-'));
  let browser;
  try {
    browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',
      chromiumSandbox:process.env.CHROMIUM_SANDBOX==='1'});
    const context=await browser.newContext({offline:true,reducedMotion:'reduce',viewport:{width:390,height:844}});
    const page=await context.newPage(),requests=[],errors=[];
    page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});
    page.on('pageerror',e=>errors.push(String(e)));
    await page.goto(pathToFileURL(path.resolve(output)).href);
    await page.locator('#record').waitFor();
    assert.equal(await page.locator('form').count(),0);
    assert.equal(await page.locator('#choices button').count(),3);
    for(const id of ['integrity','migration','unsupported']){
      const before=JSON.parse(await readFile(path.join(product,'evidence',id+'-run.json'),'utf8'));
      await page.locator('[data-mission="'+id+'"]').click();
      assert.equal(await page.locator('#purpose').textContent(),before.mission.purpose);
      assert.match(await page.locator('#verdict').textContent(),/Recorded replay/);
      assert.equal(await page.locator('[aria-pressed=true]').count(),1);
      assert.equal(await page.locator('#events li').count(),before.events.length);
      assert.equal(await page.locator('#delivery').isHidden(),id==='unsupported');
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
      if(id!=='unsupported'){
        const destination=path.join(scratch,id+'.zip');
        const ready=page.waitForEvent('download');await page.locator('#archive').click();
        const file=await ready;assert.equal(file.suggestedFilename(),id+'-artifact.zip');
        await file.saveAs(destination);
        assert.deepEqual(await readFile(destination),await readFile(path.join(product,'evidence',file.suggestedFilename())));
      }
      assert.equal(await page.locator('a[href^="http"]').count(),0);
    }
    assert.deepEqual(requests,[]);assert.deepEqual(errors,[]);
    console.log('Standalone file qualification passed for three public records and two byte-identical ZIP downloads with network disabled.');
  } finally {if(browser)await browser.close();await rm(scratch,{recursive:true,force:true});}
}
main().catch(e=>{console.error(e);process.exitCode=1;});
