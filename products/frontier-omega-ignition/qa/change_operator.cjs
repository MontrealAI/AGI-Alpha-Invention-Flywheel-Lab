"use strict";
const assert = require("node:assert/strict");
const path = require("node:path");
const {execFileSync} = require("node:child_process");

async function qualifyChangeDesk(page, work, assertLayout, receive) {
  const origin = new URL(page.url()).origin;
  await page.goto(origin + "/");
  await page.locator('a[href="/change-desk"]').click();
  await page.locator("#build:enabled").waitFor();
  await assertLayout(page, 320);
  await page.locator("#beneficiary").fill("Private archival programme");
  await page.locator("#build").click();
  await page.locator("#kit[href]").waitFor();
  assert.match(await page.locator("#verdict").textContent(), /2 notices issued/);
  assert.equal(await page.locator("#decisions tr").count(), 8);
  assert.equal(await page.locator("#decisions td", {hasText: "Awaiting repeat"}).count(), 2);
  const first = await page.locator("#kit").getAttribute("href");
  const digest = (await page.locator("#verify-command").textContent()).split(" ").at(-1);
  const zip = path.join(work, "dated-queue.zip"), extracted = path.join(work, "dated-queue");
  await receive(page, "#kit", zip);
  execFileSync("python3", ["-m", "zipfile", "-e", zip, extracted]);
  const checked = JSON.parse(execFileSync("python3", ["-IB", path.join(extracted, "review_change.py"), "--expect-queue", digest]));
  assert.equal(checked.issued, 2);
  await page.locator("#language").click();
  assert.equal(await page.locator("html").getAttribute("lang"), "fr");
  assert.match(await page.locator("h1").textContent(), /variation du ciel/);
  await page.locator('[data-instant="2026-10-29T00:00:00Z"]').click();
  assert.equal(await page.locator("#kit").getAttribute("href"), null);
  await page.locator("#build").click();
  await page.locator('#kit[href$="version=2"]').waitFor();
  assert.equal(await page.locator("#decisions td", {hasText: "avant l’échéance"}).count(), 2);
  assert.equal((await page.request.get(origin + first)).status(), 409);
  await page.locator("#second-archive").check();
  await page.locator("#build").click();
  await page.locator('#kit[href$="version=3"]').waitFor();
  assert.equal(await page.locator("#archive-heading").isVisible(), true);
  assert.match(await page.locator("#second-verdict").textContent(), /ALeRCE · 2/);
  assert.equal(await page.locator("#decisions td", {hasText: "avant l’échéance"}).count(), 2);
  await page.locator("#arm").selectOption("early_cold");
  await page.locator("#build").click();
  await page.locator('#kit[href$="version=4"]').waitFor();
  assert.match(await page.locator("#verdict").textContent(), /^0 avis émis$/);
  await page.reload();
  await page.locator('#kit[href$="version=4"]').waitFor();
  assert.equal(await page.locator("#second-archive").isChecked(), true);
  assert.equal(await page.locator("#beneficiary").inputValue(), "Private archival programme");
  await page.locator("#history summary").click();
  assert.equal(await page.locator("#revisions li").count(), 4);
  await assertLayout(page, 390);
  await assertLayout(page, 1280);
  await page.locator("#new").click();
  assert.equal(await page.locator("#kit").getAttribute("href"), null);
  assert.equal(new URL(page.url()).hash, "");
}
module.exports = {qualifyChangeDesk};
