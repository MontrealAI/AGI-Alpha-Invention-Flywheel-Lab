"""Typed complete offers whose methods and scope govern actual production.

These initial offer constructions are developer-authored hypotheses. Column-role
plans are generated by the intake instrument; neither is autonomous novelty.
"""
import copy
import hashlib
import json
import math
from pathlib import Path

PRIMITIVE_SERVICES = ('reconciliation', 'kpi_variance', 'evidence_matrix')
SERVICES = PRIMITIVE_SERVICES + ('operations_bundle','receivables_packet')
FIELDS = {'id', 'service_id', 'segment', 'qualification', 'problem', 'outcome', 'scope',
          'method', 'production_pipeline', 'verification', 'price_microUSD', 'payment',
          'renewal', 'remedy', 'deadline_hours', 'support', 'channel', 'context',
          'capacity_units', 'upfront_cost_microUSD', 'later_liabilities', 'applicability',
          'provenance', 'falsifiers', 'evidence'}
PUBLIC_METADATA = {'human_anchor_microUSD', 'production_cost_microUSD', 'quote_cost_microUSD',
                   'onboarding_cost_microUSD', 'payment_fee_bps', 'payment_fixed_microUSD',
                   'applicable_job_ids', 'delivery_hours', 'evidence_level'}


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':'), allow_nan=False).encode()).hexdigest()


def validate_offer(offer):
    if not isinstance(offer, dict) or not FIELDS <= set(offer) or set(offer) - FIELDS - PUBLIC_METADATA or offer.get('service_id') not in SERVICES:
        raise ValueError('EXACT_COMPLETE_OFFER_SCHEMA_REQUIRED')
    for key in ['id', 'segment', 'problem', 'outcome', 'verification', 'payment', 'renewal', 'remedy', 'support', 'channel', 'context', 'provenance']:
        if not isinstance(offer[key], str) or not offer[key].strip():
            raise ValueError('COMPLETE_OFFER_TEXT_REQUIRED:' + key)
    if offer['scope'] not in {'complete_outcome', 'intake_readiness'} or offer['method'] not in {'canonical', 'generated_schema', 'staged_readiness','operations_bundle','receivables_packet'}:
        raise ValueError('EXECUTABLE_OFFER_METHOD_AND_SCOPE_REQUIRED')
    if (offer['method'] == 'staged_readiness') != (offer['scope'] == 'intake_readiness'):
        raise ValueError('STAGED_SCOPE_MUST_BE_EXPLICIT')
    for key in ['price_microUSD', 'capacity_units', 'upfront_cost_microUSD', 'deadline_hours']:
        if type(offer[key]) is not int or (offer[key] < 1 or (not key.endswith('_microUSD') and offer[key] > 10**12)):
            raise ValueError('POSITIVE_INTEGER_OFFER_RESOURCE_REQUIRED:' + key)
    for key in ['qualification', 'production_pipeline', 'later_liabilities', 'applicability', 'falsifiers', 'evidence']:
        if not isinstance(offer[key], list) or not offer[key] or any(not isinstance(x, str) or not x for x in offer[key]):
            raise ValueError('NONEMPTY_OFFER_CONSTRAINT_LIST_REQUIRED:' + key)
    expected = {'canonical': ['validate_canonical_input', 'execute_service', 'independent_acceptance'],
                'generated_schema': ['infer_typed_mapping', 'execute_mapping', 'execute_service', 'independent_acceptance'],
                'staged_readiness': ['infer_typed_mapping', 'report_missing_or_ambiguous_facts', 'independent_acceptance'],
                'operations_bundle':['execute_distinct_components','independent_joint_acceptance'],
                'receivables_packet':['reconcile_common_source','derive_aging_and_kpi','construct_evidence_memo','independent_packet_acceptance']}
    if offer['production_pipeline'] != expected[offer['method']]:
        raise ValueError('METHOD_MUST_MATCH_EXECUTABLE_PIPELINE')
    if (offer['service_id']=='operations_bundle')!=(offer['method']=='operations_bundle'):
        raise ValueError('BUNDLE_REQUIRES_QUALIFIED_COMBINED_METHOD')
    if (offer['service_id']=='receivables_packet')!=(offer['method']=='receivables_packet'):
        raise ValueError('PACKET_REQUIRES_QUALIFIED_COHERENT_METHOD')
    if offer['capacity_units']!=(3 if offer['service_id'] in {'operations_bundle','receivables_packet'} else 1):
        raise ValueError('CAPACITY_MUST_MATCH_ACTUAL_COMPONENT_PRODUCTION')
    for key in set(offer) & (PUBLIC_METADATA - {'applicable_job_ids', 'evidence_level'}):
        if type(offer[key]) not in {int,float} or not math.isfinite(offer[key]) or offer[key]<0:
            raise ValueError('FINITE_PUBLIC_OFFER_METADATA_REQUIRED')
    if 'applicable_job_ids' in offer and (not isinstance(offer['applicable_job_ids'],list) or any(not isinstance(x,str) for x in offer['applicable_job_ids'])):
        raise ValueError('PUBLIC_JOB_APPLICABILITY_REQUIRED')
    return offer


def offer_catalog(*, include_packet=False):
    offers = []
    for service in PRIMITIVE_SERVICES:
        for method, scope, price in [('canonical', 'complete_outcome', 35_000_000),
                                     ('generated_schema', 'complete_outcome', 40_000_000),
                                     ('staged_readiness', 'intake_readiness', 12_000_000)]:
            pipeline = {'canonical': ['validate_canonical_input', 'execute_service', 'independent_acceptance'],
                        'generated_schema': ['infer_typed_mapping', 'execute_mapping', 'execute_service', 'independent_acceptance'],
                        'staged_readiness': ['infer_typed_mapping', 'report_missing_or_ambiguous_facts', 'independent_acceptance']}[method]
            offer = {'id': service + ':' + method, 'service_id': service,
                     'segment': 'permission-qualified synthetic small digital operator',
                     'qualification': ['public or synthetic source only', 'explicit USD units', 'customer chooses the stated scope'],
                     'problem': 'Source export schema or missing facts prevent a checked complete digital outcome.',
                     'outcome': service + ' source-bound completed packet' if scope == 'complete_outcome' else 'Source-bound intake readiness and unresolved-fact packet only',
                     'scope': scope, 'method': method, 'production_pipeline': pipeline,
                     'verification': 'Independent raw-source, normalization, row-conservation and service-specific outcome checker',
                     'price_microUSD': price, 'payment': 'Simulated protected payment, acceptance before settled release',
                     'renewal': 'Optional repeat decision; no guaranteed future purchase',
                     'remedy': 'Reject unsupported output; one bounded correction or simulated refund',
                     'deadline_hours': 24, 'support': 'One source-bound correction and documented limitations',
                     'channel': 'Simulated finite qualified inbound or context-authorized repeat offer',
                     'context': 'Reuse authorized synthetic customer context; do not infer private access',
                     'capacity_units': 1, 'upfront_cost_microUSD': 2_000_000,
                     'later_liabilities': ['payment fee', 'correction and support budget', 'native refund tail reserve'],
                     'applicability': ['Explicitly typed source export', 'No legal, clinical, credential or eligibility judgment'],
                     'provenance': 'Developer-authored initial complete-offer hypothesis; generated instrument plans separately attributed',
                     'falsifiers': ['Unsupported facts', 'Ambiguous mapping', 'Failed independent acceptance', 'Negative complete-cost contribution'],
                     'evidence': ['Initial offer hypothesis; execution receipt required before admission']}
            offers.append(validate_offer(offer))
    bundle=copy.deepcopy(offers[0])
    bundle.update(id='operations_bundle:operations_bundle',service_id='operations_bundle',method='operations_bundle',
                  problem='One qualified operator needs three related source-bound digital outcomes without duplicate acquisition or component sales.',
                  outcome='One complete operations packet: checked reconciliation, KPI variance and evidence matrix.',
                  production_pipeline=['execute_distinct_components','independent_joint_acceptance'],
                  price_microUSD=100_000_000,capacity_units=3,upfront_cost_microUSD=6_000_000,
                  verification='Independent joint checker verifies every source-bound component and exact shared work identities.',
                  applicability=['All three primitive contracts independently qualify complete outcomes','The same component work may not be sold twice'],
                  falsifiers=['Any failed component acceptance','Duplicate work identity','Unfunded joint obligation','Negative complete-cost bundle contribution'])
    offers.append(validate_offer(bundle))
    if include_packet:
        packet=copy.deepcopy(bundle)
        packet.update(id='receivables_packet:receivables_packet',service_id='receivables_packet',method='receivables_packet',
            problem='One authorized entity and period requires a coherent source-bound receivables outcome.',
            outcome='Reconciled receivables, derived aging/KPI and evidence-backed exception memo from one source.',
            production_pipeline=['reconcile_common_source','derive_aging_and_kpi','construct_evidence_memo','independent_packet_acceptance'],
            verification='Independent packet checker rederives all three components and their shared source/entity/period bindings.',
            applicability=['One explicit entity and period','Same source rows feed all three components','Voluntary request accepts the complete receivables scope'])
        offers.append(validate_offer(packet))
    return offers


def adapt_offer(offer, criticism, *, instrument_budget_microUSD=5_000_000):
    """Make an explicit, costed method or promised-scope change from evidence."""
    result = copy.deepcopy(validate_offer(offer))
    if not isinstance(criticism,dict) or criticism.get('verified') is not True or criticism.get('kind') not in {'schema_mismatch','missing_information','ambiguous_mapping'}:
        raise ValueError('VERIFIED_EXECUTABLE_CRITICISM_REQUIRED')
    expected=_adjudicate(offer,criticism.get('raw_order'),criticism.get('rejected_artifact'))
    if criticism!=expected:
        raise ValueError('CRITICISM_MUST_MATCH_RECOMPUTED_SOURCE_EVIDENCE')
    if type(instrument_budget_microUSD) is not int or instrument_budget_microUSD < 1:
        raise ValueError('POSITIVE_CONSTRUCTION_ALLOCATION_REQUIRED')
    target_method = 'generated_schema' if criticism['kind'] == 'schema_mismatch' else 'staged_readiness'
    target = next(x for x in offer_catalog() if x['service_id'] == offer['service_id'] and x['method'] == target_method)
    result.update({key: copy.deepcopy(target[key]) for key in ['scope', 'method', 'production_pipeline', 'outcome', 'price_microUSD']})
    result['id'] = offer['id'] + ':adapted:' + digest(criticism)[:12]
    result['upfront_cost_microUSD'] += instrument_budget_microUSD
    result['evidence'] = result['evidence'] + ['Verified criticism:' + digest(criticism)]
    result['provenance'] = 'Developer-authored adaptation rule executed on source-grounded criticism; mapping itself generated at execution.'
    return validate_offer(result)


def _adjudicate(offer,raw_order,rejected_artifact):
    from adaptive_enterprise.checkers import audit_delivery
    from adaptive_enterprise.instruments import produce
    validate_offer(offer)
    if not isinstance(raw_order,dict) or raw_order.get('service_id')!=offer['service_id'] or not isinstance(rejected_artifact,dict):
        raise ValueError('SCOPED_REJECTED_INPUT_AND_ARTIFACT_REQUIRED')
    receipt=audit_delivery(offer['service_id'],raw_order,rejected_artifact)
    errors=list(receipt['errors'])
    if rejected_artifact.get('method')!=offer['method']:
        errors.append('PROMISED_PRODUCTION_METHOD_NOT_DELIVERED')
    if rejected_artifact.get('outcome_scope')!=offer['scope']:
        errors.append('PROMISED_OUTCOME_SCOPE_NOT_DELIVERED')
    receipt={**receipt,'accepted':not errors,'errors':sorted(set(errors)), 'offer_sha256':digest(offer)}
    if receipt['accepted']:
        raise ValueError('ACCEPTED_WORK_IS_NOT_VERIFIED_CRITICISM')
    try:
        original_execution=produce(raw_order,offer['method'])
    except (ValueError,KeyError,TypeError) as error:
        original_rejection=str(error)
    else:
        original_check=audit_delivery(offer['service_id'],raw_order,original_execution)
        if original_check['accepted']:
            raise ValueError('ORIGINAL_OFFER_EXECUTES_WITHOUT_THIS_REPAIR')
        original_rejection=';'.join(original_check['errors'])
    plan=rejected_artifact.get('plan',{})
    if plan.get('status')=='BLOCKED':
        kind='ambiguous_mapping' if plan.get('failure')=='AMBIGUOUS_MAPPING' else 'missing_information'
    elif offer['method']=='canonical' and rejected_artifact.get('method')=='generated_schema':
        kind='schema_mismatch'
    else:
        raise ValueError('REJECTION_DOES_NOT_ESTABLISH_THIS_STRUCTURAL_REPAIR')
    source_root=Path(__file__).resolve().parent
    sources={name:hashlib.sha256((source_root/name).read_bytes()).hexdigest() for name in ['checkers.py','instruments.py','strategies.py']}
    return {'schema':'adaptive012/adjudicated-criticism/v1','verified':True,'kind':kind,
            'rejected_offer':copy.deepcopy(offer),
            'raw_order':copy.deepcopy(raw_order),'rejected_artifact':copy.deepcopy(rejected_artifact),'rejection_receipt':receipt,
            'source_sha256':digest(raw_order),'rejected_artifact_sha256':digest(rejected_artifact),'rejection_receipt_sha256':digest(receipt),
            'offer_sha256':digest(offer),'source_hashes':sources,
            'original_method_reexecution_rejection':original_rejection,
            'scope':'Recomputed fixed-checker and promised-contract rejection. Classification is developer-authored; it is not autonomous discovery.'}


def adjudicate_and_adapt(raw_order,offer,rejected_artifact,rejection_receipt=None,*,instrument_budget_microUSD=5_000_000):
    """Preserve failed evidence, recompute adjudication, execute and check repair."""
    from adaptive_enterprise.instruments import produce
    from adaptive_enterprise.checkers import audit_delivery
    adjudication=_adjudicate(offer,raw_order,rejected_artifact)
    if rejection_receipt is not None and rejection_receipt!=adjudication['rejection_receipt']:
        raise ValueError('SUPPLIED_REJECTION_RECEIPT_MISMATCH')
    adapted=adapt_offer(offer,adjudication,instrument_budget_microUSD=instrument_budget_microUSD)
    repaired=produce(raw_order,adapted['method'])
    checked=audit_delivery(adapted['service_id'],raw_order,repaired)
    if not checked['accepted'] or repaired['outcome_scope']!=adapted['scope']:
        raise ValueError('ADJUDICATED_REPAIR_FAILED_INDEPENDENT_ACCEPTANCE')
    chain={'schema':'adaptive012/criticism-repair-chain/v1','adjudication':adjudication,'adapted_offer':adapted,
           'repaired_artifact':repaired,'repair_acceptance':checked,'repair_artifact_sha256':digest(repaired),
           'construction_allocation_microUSD':instrument_budget_microUSD,
           'cost_evidence':'Declared bounded construction envelope; no inferred model bill or human hour.'}
    return {**chain,'chain_sha256':digest(chain)}
