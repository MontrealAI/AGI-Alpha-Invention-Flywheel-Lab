/** Executable teaching fixture. Credits and prices are assumptions, not observations. */
export const COST = Object.freeze({start:10,build:4,verify:2,deliver:2,payment:13,reinvest:4,nextBase:5,adapter:2,replace:4});
export const CASES = Object.freeze({
  first:Object.freeze([[110,12,100],[115,10,100],[85,12,95],[101,1,100]].map(Object.freeze)),
  next:Object.freeze([[114,10,2,50],[110,10,2,50],[105,5,2,50],[91,7,2,48],[130,4,3,42]].map(Object.freeze))
});

export function runDoubleFlywheel({rejectFirst=false}={}) {
  // Each tuple is raw, offset, [scale], threshold. Equality belongs to "ordinary".
  const decide=(n,d,t)=>n>d*t;
  const first=CASES.first.map(([r,o,t])=>decide(r-o,1,t));
  if(rejectFirst) first[2]=!first[2];
  // Frozen controls were derived separately, not generated by the candidate.
  const expectedFirst=[false,true,false,false], expectedNext=[true,false,false,false,false];
  const acceptedFirst=first.every((v,i)=>v===expectedFirst[i]);
  const cost1=COST.build+COST.verify+(acceptedFirst?COST.deliver:0);
  const receipts=acceptedFirst?COST.payment:0;
  const surplus=receipts-cost1;
  const reinvestment=acceptedFirst?Math.min(Math.max(surplus,0),COST.reinvest):0;
  const budget2=COST.nextBase+reinvestment;
  const reusable=acceptedFirst;
  // Fresh arm also uses a competent exact comparator; only setup charges differ.
  const fresh=CASES.next.map(([r,o,s,t])=>(r-o)/s>t);
  const next=reusable?CASES.next.map(([r,o,s,t])=>decide(r-o,s,t)):null;
  const freshCost=COST.adapter+COST.replace+COST.verify+COST.deliver;
  const retainedCost=COST.adapter+COST.verify+COST.deliver;
  const passes=x=>x!==null&&x.every((v,i)=>v===expectedNext[i]);
  // Counterfactuals hold the second problem and oracle fixed and remove only one loop.
  const scenario=(budget,cost,correct)=>({budget,cost,correct,eligible:correct&&cost<=budget});
  const counterfactuals=reusable ? {
    tool:scenario(COST.nextBase,retainedCost,passes(next)),
    fund:scenario(budget2,freshCost,passes(fresh)),
    both:scenario(budget2,retainedCost,passes(next))
  } : null;
  return {
    version:1, scope:'SIMULATION', acceptedFirst, checks:first, expectedFirst,
    budget1:COST.start, cost1, receipts, surplus, reinvestment, retainedSurplus:Math.max(surplus,0)-reinvestment,
    reusable, counterfactuals, budget2, freshCost, retainedCost, fresh, next, expectedNext,
    freshEligible:passes(fresh)&&freshCost<=budget2,
    retainedEligible:passes(next)&&retainedCost<=budget2,
    retainedBudgetRemaining:passes(next)&&retainedCost<=budget2?budget2-retainedCost:null
  };
}

/** One controlled intervention. Verification and sensor data never change across arms. */
export function selectFlywheelState(run, keep, invest) {
  const budget=COST.nextBase+(invest?run.reinvestment:0);
  const cost=keep&&run.reusable?run.retainedCost:run.freshCost;
  const verified=run.acceptedFirst&&(keep?run.next:run.fresh)?.every((v,i)=>v===run.expectedNext[i]);
  const open=Boolean(verified&&budget>=cost);
  return {budget,cost,open,gap:budget-cost};
}

